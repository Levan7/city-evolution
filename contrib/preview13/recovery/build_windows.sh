#!/bin/bash
set -e
source preview13-work/env.sh
export PATH="$TASK_ROOT/win-tools/usr/bin:$PATH"
export WINPREFIX="$TASK_ROOT/win-prefix"
unset CFLAGS CXXFLAGS LDFLAGS PKG_CONFIG_PATH
export PKG_CONFIG_LIBDIR="$WINPREFIX/lib/pkgconfig"
mkdir -p "$WINPREFIX"
cat > "$TASK_ROOT/windows-toolchain.cmake" <<EOF
set(CMAKE_SYSTEM_NAME Windows)
set(CMAKE_SYSTEM_PROCESSOR x86_64)
set(CMAKE_C_COMPILER $TASK_ROOT/win-tools/usr/bin/x86_64-w64-mingw32-gcc-posix)
set(CMAKE_CXX_COMPILER $TASK_ROOT/win-tools/usr/bin/x86_64-w64-mingw32-g++-posix)
set(CMAKE_RC_COMPILER $TASK_ROOT/win-tools/usr/bin/x86_64-w64-mingw32-windres)
set(CMAKE_FIND_ROOT_PATH $WINPREFIX $TASK_ROOT/win-tools/usr/x86_64-w64-mingw32)
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
EOF
get(){ [ -d "$TASK_ROOT/deps/$3" ] || { curl -fLsS --retry 2 --max-time 120 "https://codeload.github.com/$1/tar.gz/$2" -o "$TASK_ROOT/deps/$3.tar.gz"; tar xzf "$TASK_ROOT/deps/$3.tar.gz" -C "$TASK_ROOT/deps"; }; }
get madler/zlib refs/tags/v1.3.1 zlib-1.3.1
get GNOME/libxml2 refs/tags/v2.12.9 libxml2-2.12.9
get freetype/freetype refs/tags/VER-2-13-3 freetype-VER-2-13-3
build(){ local src=$1; shift; cmake -S "$TASK_ROOT/deps/$src" -B "$TASK_ROOT/win-build-$src" -G Ninja -DCMAKE_BUILD_TYPE=Release -DCMAKE_TOOLCHAIN_FILE="$TASK_ROOT/windows-toolchain.cmake" -DCMAKE_INSTALL_PREFIX="$WINPREFIX" -DCMAKE_PREFIX_PATH="$WINPREFIX" "$@" && cmake --build "$TASK_ROOT/win-build-$src" -j6 && cmake --install "$TASK_ROOT/win-build-$src"; }
build zlib-1.3.1 -DBUILD_SHARED_LIBS=OFF -DZLIB_BUILD_EXAMPLES=OFF
cp "$WINPREFIX/lib/libzlibstatic.a" "$WINPREFIX/lib/libz.a"
build libxml2-2.12.9 -DBUILD_SHARED_LIBS=ON -DLIBXML2_WITH_PYTHON=OFF -DLIBXML2_WITH_ICONV=OFF -DLIBXML2_WITH_LZMA=OFF -DLIBXML2_WITH_TESTS=OFF -DLIBXML2_WITH_PROGRAMS=OFF -DLIBXML2_WITH_HTTP=OFF -DLIBXML2_WITH_ZLIB=ON
build freetype-VER-2-13-3 -DBUILD_SHARED_LIBS=OFF -DFT_DISABLE_ZLIB=ON -DFT_DISABLE_BZIP2=ON -DFT_DISABLE_PNG=ON -DFT_DISABLE_HARFBUZZ=ON -DFT_DISABLE_BROTLI=ON
build SDL-release-3.4.0 -DSDL_SHARED=ON -DSDL_STATIC=OFF -DSDL_TESTS=OFF -DSDL_EXAMPLES=OFF
build SDL_image-release-3.2.4 -DSDLIMAGE_VENDORED=OFF -DSDLIMAGE_BACKEND_STB=ON -DSDLIMAGE_PNG=ON -DSDLIMAGE_JPG=ON -DSDLIMAGE_AVIF=OFF -DSDLIMAGE_TIF=OFF -DSDLIMAGE_WEBP=OFF -DSDLIMAGE_JXL=OFF
build SDL_ttf-release-3.2.2 -DSDLTTF_VENDORED=OFF -DSDLTTF_HARFBUZZ=OFF -DSDLTTF_PLUTOSVG=OFF -DSDLTTF_SAMPLES=OFF
build SDL_mixer-main -DSDLMIXER_VENDORED=OFF -DSDLMIXER_OPUS=OFF -DSDLMIXER_MIDI=OFF -DSDLMIXER_GME=OFF -DSDLMIXER_WAVPACK=OFF -DSDLMIXER_MOD=OFF -DSDLMIXER_FLAC=OFF -DSDLMIXER_MP3=OFF -DSDLMIXER_VORBIS_VORBISFILE=OFF -DSDLMIXER_VORBIS_STB=ON -DSDLMIXER_SAMPLES=OFF -DSDLMIXER_EXAMPLES=OFF -DSDLMIXER_TESTS=OFF
cmake -S "$TASK_ROOT/CityEvolution-Preview-13-Source" -B "$TASK_ROOT/win-build" -G Ninja -DCMAKE_TOOLCHAIN_FILE="$TASK_ROOT/windows-toolchain.cmake" -DCMAKE_BUILD_TYPE=Release -DCMAKE_PREFIX_PATH="$WINPREFIX" -DENABLE_NLS=OFF -DLINCITYNG_RELOCATABLE=ON -DLINCITYNG_EVOLUTION_CHECKS=ON -DLINCITYNG_VERSION_SUFFIX=Preview-13
cmake --build "$TASK_ROOT/win-build" -j6
